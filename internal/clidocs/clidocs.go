// Package clidocs renders the finfocus command tree as Starlight Markdown
// pages, one per command, for the generated CLI reference. It is used by
// tools/gendocs and is not part of the shipped binary.
package clidocs

import (
	"bytes"
	"context"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/rshade/ax-go"
	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
	"gopkg.in/yaml.v3"

	"github.com/rshade/finfocus/internal/cli"
)

// OutputDir is the generated reference directory, relative to the repository root.
const OutputDir = "docs/src/content/docs/reference/cli"

// docsVersion is the version the generator stamps on the root command. Cobra
// only uses it for the --version flag, whose help text does not include it,
// so a fixed value keeps the output independent of how the tool was built.
const docsVersion = "docs"

const frontMatterIndent = 2

const generatedNotice = "<!-- Generated by `make docs-cli` from the cobra command tree. Do not edit. -->"

// NewRoot builds the finfocus root command the way cmd/finfocus does and
// returns it with everything ax.Execute mounts: the --format, --dry-run,
// --yes, --strict, and --idempotency-key persistent flags, and Cobra's help
// and completion commands. It runs the root with --help, which never reaches
// a PersistentPreRunE, so no configuration, home directory, or plugin is
// read. Args and environment are fixed so plugin mode and the caller's
// environment cannot change the tree.
func NewRoot() (*cobra.Command, error) {
	root := cli.NewRootCmdWithArgs(docsVersion, []string{"finfocus"},
		func(string) (string, bool) { return "", false })
	root.SetArgs([]string{"--help"})
	code := ax.Execute(context.Background(), root,
		ax.WithVersion(docsVersion),
		ax.WithStdin(strings.NewReader("")),
		ax.WithStdout(io.Discard),
		ax.WithStderr(io.Discard),
		ax.WithEnv(func(string) string { return "" }),
		ax.WithStdoutIsTTY(false),
	)
	if code != ax.ExitSuccess {
		return nil, fmt.Errorf("building the command tree: --help exited %d", code)
	}
	root.SetArgs(nil)
	return root, nil
}

// Documented reports whether cmd gets a page. It is the filter
// cobra/doc.GenMarkdownTreeCustom applies: hidden, deprecated, and help
// commands are left out.
func Documented(cmd *cobra.Command) bool {
	return cmd.IsAvailableCommand() && !cmd.IsAdditionalHelpTopicCommand()
}

// Commands returns root and every documented descendant, depth first with
// children sorted by name. That order is the sidebar order.
func Commands(root *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	var walk func(*cobra.Command)
	walk = func(c *cobra.Command) {
		out = append(out, c)
		children := append([]*cobra.Command(nil), c.Commands()...)
		sort.Slice(children, func(i, j int) bool { return children[i].Name() < children[j].Name() })
		for _, child := range children {
			if Documented(child) {
				walk(child)
			}
		}
	}
	walk(root)
	return out
}

// FileName is the page file name cobra/doc uses for cmd, such as
// finfocus_cost_projected.md.
func FileName(cmd *cobra.Command) string {
	return strings.ReplaceAll(cmd.CommandPath(), " ", "_") + ".md"
}

// Render returns every page keyed by file name.
func Render(root *cobra.Command) (map[string][]byte, error) {
	pages := make(map[string][]byte)
	for i, c := range Commands(root) {
		page, err := renderPage(c, i+1)
		if err != nil {
			return nil, fmt.Errorf("rendering %s: %w", c.CommandPath(), err)
		}
		pages[FileName(c)] = page
	}
	return pages, nil
}

// Write replaces the Markdown pages in dir with pages. A page whose command
// no longer exists is removed, so a deleted command cannot leave a stale page.
func Write(dir string, pages map[string][]byte) error {
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return fmt.Errorf("creating %s: %w", dir, err)
	}
	existing, err := filepath.Glob(filepath.Join(dir, "*.md"))
	if err != nil {
		return fmt.Errorf("listing %s: %w", dir, err)
	}
	for _, path := range existing {
		if _, keep := pages[filepath.Base(path)]; keep {
			continue
		}
		if rmErr := os.Remove(path); rmErr != nil {
			return fmt.Errorf("removing stale page: %w", rmErr)
		}
	}
	for name, page := range pages {
		if writeErr := os.WriteFile(filepath.Join(dir, name), page, 0o600); writeErr != nil {
			return fmt.Errorf("writing %s: %w", name, writeErr)
		}
	}
	return nil
}

type frontMatter struct {
	Title       string `yaml:"title"`
	Description string `yaml:"description"`
	// EditURL is always false: the page's source is Go help text, not this file.
	EditURL bool    `yaml:"editUrl"`
	Sidebar sidebar `yaml:"sidebar"`
}

type sidebar struct {
	Label string `yaml:"label"`
	Order int    `yaml:"order"`
}

func renderPage(cmd *cobra.Command, order int) ([]byte, error) {
	var page bytes.Buffer
	page.WriteString("---\n")
	enc := yaml.NewEncoder(&page)
	enc.SetIndent(frontMatterIndent)
	if err := enc.Encode(frontMatter{
		Title:       cmd.CommandPath(),
		Description: cmd.Short,
		Sidebar:     sidebar{Label: sidebarLabel(cmd), Order: order},
	}); err != nil {
		return nil, fmt.Errorf("front matter: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("front matter: %w", err)
	}
	page.WriteString("---\n\n")
	page.WriteString(generatedNotice + "\n\n")

	long, autoGen := cmd.Long, cmd.DisableAutoGenTag
	cmd.Long, cmd.DisableAutoGenTag = fencedLong(long), true
	defer func() { cmd.Long, cmd.DisableAutoGenTag = long, autoGen }()

	var body bytes.Buffer
	if err := doc.GenMarkdownCustom(cmd, &body, linkHandler); err != nil {
		return nil, err
	}
	page.WriteString(withAliases(toStarlight(body.String()), cmd.Aliases))
	return page.Bytes(), nil
}

// withAliases adds the command's aliases after the short description, the
// first paragraph. cobra/doc leaves them out, but --help lists them.
func withAliases(body string, aliases []string) string {
	if len(aliases) == 0 {
		return body
	}
	short, rest, _ := strings.Cut(body, "\n\n")
	return short + "\n\nAliases: `" + strings.Join(aliases, "`, `") + "`\n\n" + rest
}

// sidebarLabel drops the root name, which every page shares, so the sidebar
// reads "cost projected" rather than "finfocus cost projected".
func sidebarLabel(cmd *cobra.Command) string {
	if !cmd.HasParent() {
		return cmd.Name()
	}
	return strings.TrimPrefix(cmd.CommandPath(), cmd.Root().Name()+" ")
}

// linkHandler keeps cobra's file-to-file links relative, like every other
// docs page. The docs sites' relative-md-links plugin turns them into
// Starlight routes under whatever base the site uses, and they still browse
// on GitHub.
func linkHandler(name string) string {
	return "./" + name
}
